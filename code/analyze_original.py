"""Experiment 1: aggregate the blinded judge scores for the ORIGINAL Schroter test papers (data_original/).
Same scoring and statistics as analyze.py (imported), plus paper-by-paper and error-by-paper comparison with the
published human values, which here refer to the very same manuscripts.
Inputs:  data_original/manifest.json, data_original/judgements/oreview_XXX__J{1,2}.json, data_original/reviews/*.md
Outputs: data_original/results.json, data_original/results_summary.md
Run: python code/analyze_original.py
"""
import json, os, glob, statistics as st
from collections import Counter
import analyze as A

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data_original")

def load_rows():
    manifest = {j["id"]: j for j in json.load(open(os.path.join(D, "manifest.json")))}
    rows = []
    for rid, job in manifest.items():
        per = {}
        for jf in sorted(glob.glob(os.path.join(D, "judgements", f"{rid}__J*.json"))):
            d = json.load(open(jf))
            per[os.path.basename(jf).split("__")[1].split(".")[0]] = {
                "scores": {s["id"]: float(s["score"]) for s in d["scores"]}, "rec": d.get("recommendation", "unclear")}
        if not per:
            continue
        mean_scores = {e: st.mean([p["scores"].get(e, 0) for p in per.values()]) for e in A.ERR_IDS}
        rf = os.path.join(D, "reviews", f"{rid}.md")
        words = len(open(rf).read().split()) if os.path.exists(rf) else None
        rows.append({"id": rid, **job, "judges": per, "scores": mean_scores,
                     "rec": Counter(p["rec"] for p in per.values()).most_common(1)[0][0], "words": words})
    return rows

if __name__ == "__main__":
    rows = load_rows()
    summ = A.summarise(rows); agr = A.agreement(rows)
    tests = {}; PM = A.present(summ)
    for a in PM:
        for b in PM:
            if a < b:
                tests[f"{a}_vs_{b}"] = A.mann_whitney_p(summ[a]["totals"], summ[b]["totals"])
    # per paper x error detection (%), for the direct comparison with Schroter Table 5 (same manuscripts)
    per_paper_error = {m: {str(p): {e: 100*st.mean([r["scores"][e] for r in rows if r["model"]==m and r["paper"]==p])
                                     for e in A.ERR_IDS} for p in (1,2,3)} for m in PM}
    human_pe = {str(p): {e: A.HUMAN_PER_ERROR[e][p-1] for e in A.ERR_IDS} for p in (1,2,3)}
    res = {"experiment": "original Schroter test papers (BMJ 2004 supplement)",
           "summary": summ, "agreement": agr, "tests_total_mannwhitney_p": tests,
           "per_paper_error_pct": per_paper_error, "human_per_paper_error_pct": human_pe,
           "human_by_paper": summ["human"]["by_paper"] if "human" in summ else None,
           "rows": [{k: v for k, v in r.items() if k != "judges"} for r in rows]}
    json.dump(res, open(os.path.join(D, "results.json"), "w"), indent=1)

    L = ["# Experiment 1 (original Schroter test papers): results summary (generated by code/analyze_original.py)\n"]
    L.append(f"Judge agreement: {agr['n_pairs']} paired judgements; exact agreement {100*agr['exact_agreement']:.1f}%; "
             f"binary agreement {100*agr['binary_agreement']:.1f}%; Cohen's kappa {agr['kappa_binary']:.3f}\n")
    L.append("| Group | n reviews | Major (of 9), mean [95% CI] | % | Minor (of 5), mean [95% CI] | % | Mean words |\n|---|---|---|---|---|---|---|")
    L.append(f"| BMJ reviewers 2008 (Schroter; same papers) | 607 x 3 papers | {summ['human']['major_mean']:.2f} | {summ['human']['major_pct']:.0f} | {summ['human']['minor_mean']:.2f} | {summ['human']['minor_pct']:.0f} | - |")
    for m in PM:
        s = summ[m]
        L.append(f"| {A.MODEL_LABEL[m]} | {s['n']} | {s['major_mean']:.2f} [{s['major_ci'][0]:.2f}, {s['major_ci'][1]:.2f}] | {s['major_pct']:.0f} | "
                 f"{s['minor_mean']:.2f} [{s['minor_ci'][0]:.2f}, {s['minor_ci'][1]:.2f}] | {s['minor_pct']:.0f} | {s['words_mean']:.0f} |")
    L.append("\n## By paper (major errors of 9): humans (Schroter, same paper) vs models\n")
    L.append("| Paper | Humans | " + " | ".join(A.MODEL_LABEL[m] for m in PM) + " |\n|---|---|" + "---|"*len(PM))
    for p in (1,2,3):
        L.append(f"| {p} | {A.HUMAN_MEAN_MAJOR[p-1]:.2f} | " + " | ".join(f"{summ[m]['by_paper'][p]['major']:.2f}" for m in PM) + " |")
    L.append("\n## Per-error detection (% of reviews; mean of the two judges' 0/0.5/1 scores), all papers pooled\n")
    L.append("| Error | Humans (control group, Schroter Table 5) | " + " | ".join(A.MODEL_LABEL[m] for m in PM) + " |\n|---|---|" + "---|"*len(PM))
    for e in A.ERR_IDS:
        L.append(f"| {e} {A.ERR_NAMES[e]} | {st.mean(A.HUMAN_PER_ERROR[e]):.0f} | " + " | ".join(f"{summ[m]['per_error_pct'][e]:.0f}" for m in PM) + " |")
    L.append("\n## Recommendations\n")
    for m in PM:
        L.append(f"- {A.MODEL_LABEL[m]}: {summ[m]['recommendations']}")
    L.append("\n## Pairwise Mann-Whitney (per-review total of 14), two-sided p\n")
    for k, v in tests.items():
        L.append(f"- {k}: p = {v:.3g}")
    open(os.path.join(D, "results_summary.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))
